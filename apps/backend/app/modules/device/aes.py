"""AES-128, in pure Python, because the backend stays stdlib-only for hardware.

LG's IP Control channel (port 9761) encrypts every command with AES-128-CBC under
a key derived from the eight characters the TV shows in its IP Control menu. The
standard library ships no cipher, so this file *is* the dependency: no wheels, no
build step, just enough AES for a handful of short commands per switch.

Only what that protocol needs — 128-bit keys, ECB for the initialisation vector
and CBC for the message — and nothing else. Correctness is pinned to the FIPS-197
test vector in `tests/test_lg_ip_control.py`; do not edit this file without it.
"""

from __future__ import annotations

BLOCK = 16


def _xtime(a: int) -> int:
    a <<= 1
    return (a ^ 0x1B) & 0xFF if a & 0x100 else a


def _mul(a: int, b: int) -> int:
    """Multiply two bytes in GF(2^8) with AES's modulus."""
    out = 0
    while b:
        if b & 1:
            out ^= a
        a = _xtime(a)
        b >>= 1
    return out


def _inverse(a: int) -> int:
    if a == 0:
        return 0
    for candidate in range(1, 256):
        if _mul(a, candidate) == 1:
            return candidate
    raise AssertionError("every non-zero byte has a multiplicative inverse")


def _build_sbox() -> list[int]:
    """The S-box, derived rather than pasted, so a typo cannot hide in a table."""
    sbox = []
    for a in range(256):
        b = _inverse(a)
        s = b
        for _ in range(4):
            b = ((b << 1) | (b >> 7)) & 0xFF
            s ^= b
        sbox.append(s ^ 0x63)
    return sbox


SBOX = _build_sbox()
INV_SBOX = [0] * 256
for _index, _value in enumerate(SBOX):
    INV_SBOX[_value] = _index
RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36]


def _expand(key: bytes) -> list[list[int]]:
    if len(key) != BLOCK:
        raise ValueError("AES-128 needs a 16-byte key")
    words = [list(key[i:i + 4]) for i in range(0, BLOCK, 4)]
    for i in range(4, 44):
        word = list(words[i - 1])
        if i % 4 == 0:
            word = word[1:] + word[:1]
            word = [SBOX[b] for b in word]
            word[0] ^= RCON[i // 4 - 1]
        words.append([words[i - 4][j] ^ word[j] for j in range(4)])
    return words


def _add_round_key(state: list[list[int]], words: list[list[int]], round_no: int) -> None:
    for column in range(4):
        for row in range(4):
            state[row][column] ^= words[round_no * 4 + column][row]


def _mix_columns(state: list[list[int]], inverse: bool = False) -> None:
    for column in range(4):
        a = [state[row][column] for row in range(4)]
        if inverse:
            state[0][column] = _mul(a[0], 14) ^ _mul(a[1], 11) ^ _mul(a[2], 13) ^ _mul(a[3], 9)
            state[1][column] = _mul(a[0], 9) ^ _mul(a[1], 14) ^ _mul(a[2], 11) ^ _mul(a[3], 13)
            state[2][column] = _mul(a[0], 13) ^ _mul(a[1], 9) ^ _mul(a[2], 14) ^ _mul(a[3], 11)
            state[3][column] = _mul(a[0], 11) ^ _mul(a[1], 13) ^ _mul(a[2], 9) ^ _mul(a[3], 14)
        else:
            state[0][column] = _mul(a[0], 2) ^ _mul(a[1], 3) ^ a[2] ^ a[3]
            state[1][column] = a[0] ^ _mul(a[1], 2) ^ _mul(a[2], 3) ^ a[3]
            state[2][column] = a[0] ^ a[1] ^ _mul(a[2], 2) ^ _mul(a[3], 3)
            state[3][column] = _mul(a[0], 3) ^ a[1] ^ a[2] ^ _mul(a[3], 2)


def _shift_rows(state: list[list[int]], inverse: bool = False) -> None:
    for row in range(1, 4):
        values = [state[row][column] for column in range(4)]
        shift = -row if inverse else row
        values = values[shift:] + values[:shift]
        for column in range(4):
            state[row][column] = values[column]


def encrypt_block(words: list[list[int]], block: bytes) -> bytes:
    state = [[block[row + 4 * column] for column in range(4)] for row in range(4)]
    _add_round_key(state, words, 0)
    for round_no in range(1, 10):
        for row in range(4):
            for column in range(4):
                state[row][column] = SBOX[state[row][column]]
        _shift_rows(state)
        _mix_columns(state)
        _add_round_key(state, words, round_no)
    for row in range(4):
        for column in range(4):
            state[row][column] = SBOX[state[row][column]]
    _shift_rows(state)
    _add_round_key(state, words, 10)
    return bytes(state[row][column] for column in range(4) for row in range(4))


def decrypt_block(words: list[list[int]], block: bytes) -> bytes:
    state = [[block[row + 4 * column] for column in range(4)] for row in range(4)]
    _add_round_key(state, words, 10)
    for round_no in range(9, 0, -1):
        _shift_rows(state, inverse=True)
        for row in range(4):
            for column in range(4):
                state[row][column] = INV_SBOX[state[row][column]]
        _add_round_key(state, words, round_no)
        _mix_columns(state, inverse=True)
    _shift_rows(state, inverse=True)
    for row in range(4):
        for column in range(4):
            state[row][column] = INV_SBOX[state[row][column]]
    _add_round_key(state, words, 0)
    return bytes(state[row][column] for column in range(4) for row in range(4))


def ecb_encrypt(key: bytes, data: bytes) -> bytes:
    if len(data) % BLOCK:
        raise ValueError("ECB needs whole blocks")
    words = _expand(key)
    return b"".join(encrypt_block(words, data[i:i + BLOCK]) for i in range(0, len(data), BLOCK))


def ecb_decrypt(key: bytes, data: bytes) -> bytes:
    if len(data) % BLOCK:
        raise ValueError("ECB needs whole blocks")
    words = _expand(key)
    return b"".join(decrypt_block(words, data[i:i + BLOCK]) for i in range(0, len(data), BLOCK))


def cbc_encrypt(key: bytes, iv: bytes, data: bytes) -> bytes:
    if len(iv) != BLOCK or len(data) % BLOCK:
        raise ValueError("CBC needs a 16-byte IV and whole blocks")
    words = _expand(key)
    previous, out = iv, bytearray()
    for i in range(0, len(data), BLOCK):
        block = bytes(a ^ b for a, b in zip(data[i:i + BLOCK], previous))
        previous = encrypt_block(words, block)
        out += previous
    return bytes(out)


def cbc_decrypt(key: bytes, iv: bytes, data: bytes) -> bytes:
    if len(iv) != BLOCK or len(data) % BLOCK:
        raise ValueError("CBC needs a 16-byte IV and whole blocks")
    words = _expand(key)
    previous, out = iv, bytearray()
    for i in range(0, len(data), BLOCK):
        block = data[i:i + BLOCK]
        out += bytes(a ^ b for a, b in zip(decrypt_block(words, block), previous))
        previous = block
    return bytes(out)
